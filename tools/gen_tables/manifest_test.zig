const std = @import("std");
const manifest = @import("manifest.zig");

const gpa = std.testing.allocator;

test "parses rev, headers and tables, ignoring comments and blanks" {
    var m = try manifest.parse(gpa,
        \\# comment
        \\rev abc123
        \\
        \\header src/a.h
        \\table src/LangModels/LangX.cpp lang_x
        \\table src/Y.tab y_freq
        \\
    );
    defer m.deinit(gpa);
    try std.testing.expectEqualStrings("abc123", m.rev);
    try std.testing.expectEqual(@as(usize, 1), m.headers.len);
    try std.testing.expectEqualStrings("src/a.h", m.headers[0]);
    try std.testing.expectEqual(@as(usize, 2), m.tables.len);
    try std.testing.expectEqualStrings("src/Y.tab", m.tables[1].source);
    try std.testing.expectEqualStrings("y_freq", m.tables[1].stem);
}

test "rejects malformed manifests" {
    const bad = [_][]const u8{
        "header src/a.h\n", // missing rev
        "rev a\nrev b\n", // duplicate rev
        "rev a\ntable src/x.cpp\n", // missing stem
        "rev a\ntable src/x.cpp Bad-Stem\n", // stem not a Zig identifier fragment
        "rev a\ntable src/x.cpp x\ntable src/y.cpp x\n", // duplicate stem
        "rev a\nbogus line\n",
    };
    for (bad) |text| try std.testing.expectError(error.BadManifest, manifest.parse(gpa, text));
}

test "index imports every table module in manifest order" {
    var m = try manifest.parse(gpa, "rev r1\ntable src/A.cpp a_model\ntable src/B.tab b_freq\n");
    defer m.deinit(gpa);
    const out = try manifest.renderIndex(gpa, m);
    defer gpa.free(out);
    try std.testing.expectEqualStrings(
        \\// SPDX-License-Identifier: MPL-1.1 OR GPL-2.0-or-later OR LGPL-2.1-or-later
        \\// @generated by tools/gen_tables from manifest @ r1; do not edit.
        \\
        \\pub const a_model = @import("a_model.zig");
        \\pub const b_freq = @import("b_freq.zig");
        \\
    , out);
}
