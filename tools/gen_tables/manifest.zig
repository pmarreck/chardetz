//! The table-generation manifest: which upstream revision and which upstream
//! headers/table sources are translated, and the Zig module stem for each.
//! Line format: `rev <sha>`, `header <path>`, `table <path> <stem>`, `#` comments.
const std = @import("std");

pub const Table = struct { source: []const u8, stem: []const u8 };

pub const Manifest = struct {
    arena_state: std.heap.ArenaAllocator.State,
    rev: []const u8,
    headers: []const []const u8,
    tables: []const Table,

    pub fn deinit(self: *Manifest, gpa: std.mem.Allocator) void {
        self.arena_state.promote(gpa).deinit();
        self.* = undefined;
    }
};

fn isStem(s: []const u8) bool {
    if (s.len == 0 or !std.ascii.isLower(s[0])) return false;
    for (s) |c| if (!(std.ascii.isLower(c) or std.ascii.isDigit(c) or c == '_')) return false;
    return true;
}

pub fn parse(gpa: std.mem.Allocator, text: []const u8) !Manifest {
    var arena_impl = std.heap.ArenaAllocator.init(gpa);
    errdefer arena_impl.deinit();
    const arena = arena_impl.allocator();
    const owned = try arena.dupe(u8, text);

    var rev: ?[]const u8 = null;
    var headers: std.ArrayList([]const u8) = .empty;
    var tables: std.ArrayList(Table) = .empty;
    var lines = std.mem.splitScalar(u8, owned, '\n');
    while (lines.next()) |raw| {
        const line = std.mem.trim(u8, raw, " \t\r");
        if (line.len == 0 or line[0] == '#') continue;
        var fields = std.mem.tokenizeAny(u8, line, " \t");
        const kind = fields.next().?;
        const a = fields.next() orelse return error.BadManifest;
        const b = fields.next();
        if (fields.next() != null) return error.BadManifest;
        if (std.mem.eql(u8, kind, "rev") and b == null) {
            if (rev != null) return error.BadManifest;
            rev = a;
        } else if (std.mem.eql(u8, kind, "header") and b == null) {
            try headers.append(arena, a);
        } else if (std.mem.eql(u8, kind, "table") and b != null) {
            if (!isStem(b.?)) return error.BadManifest;
            for (tables.items) |t| if (std.mem.eql(u8, t.stem, b.?)) return error.BadManifest;
            try tables.append(arena, .{ .source = a, .stem = b.? });
        } else return error.BadManifest;
    }
    return .{
        .arena_state = arena_impl.state,
        .rev = rev orelse return error.BadManifest,
        .headers = headers.items,
        .tables = tables.items,
    };
}

/// Renders `src/tables/all.zig`, which imports every generated table module so
/// a single compile reaches all of them.
pub fn renderIndex(gpa: std.mem.Allocator, m: Manifest) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.print(gpa,
        \\// SPDX-License-Identifier: MPL-1.1 OR GPL-2.0-or-later OR LGPL-2.1-or-later
        \\// @generated by tools/gen_tables from manifest @ {s}; do not edit.
        \\
        \\
    , .{m.rev});
    for (m.tables) |t| try out.print(gpa, "pub const {s} = @import(\"{s}.zig\");\n", .{ t.stem, t.stem });
    return out.toOwnedSlice(gpa);
}
