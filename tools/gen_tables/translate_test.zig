/// Independent formatting oracle: std.zig's own renderer (what `zig fmt` uses)
/// must parse the output without errors and reproduce it unchanged.
fn expectZigFmtStable(source: []const u8) !void {
    const z = try gpa.dupeZ(u8, source);
    defer gpa.free(z);
    var tree = try std.zig.Ast.parse(gpa, z, .zig);
    defer tree.deinit(gpa);
    try std.testing.expectEqual(@as(usize, 0), tree.errors.len);
    const rendered = try tree.renderAlloc(gpa);
    defer gpa.free(rendered);
    try std.testing.expectEqualStrings(rendered, source);
}

test "translation reports every emitted declaration with its kind" {
    var symbols = try symbolsFromHeader("#define PR_TRUE true\ntypedef enum { eA = 3 } E;");
    defer symbols.deinit(gpa);
    var out = try translate.translateDetailed(gpa, &symbols, license_block ++
        \\#define SIZE 2
        \\#define RATIO (float)0.5
        \\static const PRUint8 A[SIZE] = { 1 };
        \\static const PRUint32 W[] = { PCK4BITS(1,1,1,1,1,1,1,1) };
        \\static const PRUint32 L[] = { 0 };
        \\const SequenceModel S = { A, A, 1, (float)0.5, PR_TRUE, "X" };
        \\const SMModel M = { {eA, eA, eA, eA, W}, 1, {eA, eA, eA, eA, W}, L, "Y" };
    , .{ .source_path = "src/x.cpp", .source_rev = "abc123" });
    defer out.deinit(gpa);
    const expected = [_]translate.Emitted{
        .{ .name = "SIZE", .kind = .int_const },
        .{ .name = "RATIO", .kind = .float_const },
        .{ .name = "A", .kind = .array },
        .{ .name = "W", .kind = .array },
        .{ .name = "L", .kind = .array },
        .{ .name = "S", .kind = .sequence_model },
        .{ .name = "M", .kind = .sm_model },
    };
    try std.testing.expectEqual(expected.len, out.emitted.len);
    for (expected, out.emitted) |e, got| {
        try std.testing.expectEqualStrings(e.name, got.name);
        try std.testing.expectEqual(e.kind, got.kind);
    }
}

test "C++ shim exposes each emitted declaration to the table differential" {
    const emitted = [_]translate.Emitted{
        .{ .name = "SIZE", .kind = .int_const },
        .{ .name = "RATIO", .kind = .float_const },
        .{ .name = "A", .kind = .array },
        .{ .name = "S", .kind = .sequence_model },
        .{ .name = "M", .kind = .sm_model },
    };
    const shim = try translate.renderShim(gpa, "lang_x_model", "/up/src/LangModels/LangX.cpp", &emitted);
    defer gpa.free(shim);
    try std.testing.expectEqualStrings(
        \\// @generated by tools/gen_tables: test-only shim; do not edit.
        \\#include <stddef.h>
        \\#include "/up/src/LangModels/LangX.cpp"
        \\
        \\#include "chardetz_shim.h"
        \\
        \\static const chardetz_table_ref refs[] = {
        \\    { "SIZE", CHARDETZ_INT, NULL, 0, (long long)(SIZE), 0.0 },
        \\    { "RATIO", CHARDETZ_FLOAT, NULL, 0, 0, (double)(RATIO) },
        \\    { "A", CHARDETZ_ARRAY, (const void *)A, sizeof(A), 0, 0.0 },
        \\    { "S", CHARDETZ_SEQUENCE_MODEL, (const void *)&S, sizeof(S), 0, 0.0 },
        \\    { "M", CHARDETZ_SM_MODEL, (const void *)&M, sizeof(M), 0, 0.0 },
        \\};
        \\
        \\extern "C" const chardetz_table_ref *chardetz_shim_lang_x_model(size_t *count) {
        \\    *count = sizeof(refs) / sizeof(refs[0]);
        \\    return refs;
        \\}
        \\
    , shim);
}
