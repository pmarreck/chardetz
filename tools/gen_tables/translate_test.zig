//! Authored-oracle tests for the C++ table translator. Each case feeds a small
//! uchardet-style C++ snippet and asserts the exact Zig text emitted. The
//! independent check on the real tables is the differential oracle gate.
const std = @import("std");
const translate = @import("translate.zig");

const gpa = std.testing.allocator;

const license_block =
    \\/* ***** BEGIN LICENSE BLOCK *****
    \\ * Version: MPL 1.1/GPL 2.0/LGPL 2.1
    \\ * Test block.
    \\ * ***** END LICENSE BLOCK ***** */
    \\
;

const expected_preamble =
    \\// ***** BEGIN LICENSE BLOCK *****
    \\// Version: MPL 1.1/GPL 2.0/LGPL 2.1
    \\// Test block.
    \\// ***** END LICENSE BLOCK *****
    \\//
    \\// SPDX-License-Identifier: MPL-1.1 OR GPL-2.0-or-later OR LGPL-2.1-or-later
    \\// @generated by tools/gen_tables from uchardetz src/x.cpp @ abc123; do not edit.
    \\
    \\const types = @import("types.zig");
    \\
    \\
;

fn symbolsFromHeader(header: []const u8) !translate.Symbols {
    var symbols: translate.Symbols = .empty;
    errdefer symbols.deinit(gpa);
    try translate.collectHeaderSymbols(gpa, &symbols, header);
    return symbols;
}

fn expectTranslation(header: []const u8, source: []const u8, expected_body: []const u8) !void {
    var symbols = try symbolsFromHeader(header);
    defer symbols.deinit(gpa);
    const out = try translate.translate(gpa, &symbols, source, .{ .source_path = "src/x.cpp", .source_rev = "abc123" });
    defer gpa.free(out);
    const expected = try std.mem.concat(gpa, u8, &.{ expected_preamble, expected_body });
    defer gpa.free(expected);
    try std.testing.expectEqualStrings(expected, out);
    try expectZigFmtStable(out);
}

fn expectTranslationError(header: []const u8, source: []const u8, err: anyerror) !void {
    var symbols = try symbolsFromHeader(header);
    defer symbols.deinit(gpa);
    try std.testing.expectError(err, translate.translate(gpa, &symbols, source, .{ .source_path = "src/x.cpp", .source_rev = "abc123" }));
}

